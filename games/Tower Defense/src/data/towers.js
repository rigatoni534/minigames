export const TOWER_BY_ID = Object.fromEntries(TOWERS.map((t) => [t.id, t]));

export function towerStats(def, level = 1) {
  const l = Math.max(1, Math.min(LEVELS, level)) - 1;
  const dmg = def.dmg * [1, 1.6, 2.55, 4.05, 6.4][l];
  const range = def.range * [1, 1.05, 1.1, 1.16, 1.22][l];
  const rate = def.rate * [1, 1.06, 1.12, 1.18, 1.26][l];
  const income = (def.income || 0) * [1, 1.55, 2.4, 3.7, 5.6][l];
  return {
    level,
    dmg,
    range,
    rate,
    income,
    dps: def.kind === 'laser' ? dmg : dmg * rate,
    sell: 0,
    nextCost: level < LEVELS ? def.up[level - 1] : 0,
  };
}

